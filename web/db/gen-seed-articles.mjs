// Migrates the resource articles from Markdown (src/content/resources/*.md) into
// D1, using Astro's own Markdown renderer so the body HTML matches how the site
// rendered it. Emits db/seed-articles.sql (published rows). Run:
//   node db/gen-seed-articles.mjs   (then: wrangler d1 execute … --file db/seed-articles.sql)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import { createMarkdownProcessor } from '@astrojs/markdown-remark';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', 'src', 'content', 'resources');
const processor = await createMarkdownProcessor({});

const esc = (s) => String(s ?? '').replace(/'/g, "''");
const lines = ['-- Generated by db/gen-seed-articles.mjs — resource articles migrated to D1.', 'DELETE FROM articles;'];

const files = readdirSync(dir).filter((f) => f.endsWith('.md')).sort();
for (const file of files) {
  const slug = file.replace(/\.md$/, '');
  const raw = readFileSync(join(dir, file), 'utf8');
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw);
  if (!m) throw new Error(`No frontmatter in ${file}`);
  const fm = yaml.load(m[1]);
  const { code: body } = await processor.render(m[2]);
  const date = fm.date instanceof Date ? fm.date.toISOString().slice(0, 10) : String(fm.date).slice(0, 10);
  const order = fm.indexOrder == null ? 'NULL' : Number(fm.indexOrder);
  const featured = fm.featured ? 1 : 0;
  const related = JSON.stringify(Array.isArray(fm.related) ? fm.related : []);
  lines.push(
    'INSERT INTO articles (slug,state,title,hero_image,thumbnail,excerpt,author,date,category,related,index_order,featured,body,updated_at) VALUES (' +
      `'${esc(slug)}','published','${esc(fm.title)}','${esc(fm.heroImage)}','${esc(fm.thumbnail)}','${esc(fm.excerpt)}',` +
      `'${esc(fm.author ?? 'Safe Harbours')}','${esc(date)}','${esc(fm.category)}','${esc(related)}',${order},${featured},'${esc(body)}','');`,
  );
}
writeFileSync(join(here, 'seed-articles.sql'), lines.join('\n') + '\n');
console.error(`articles migrated: ${files.length}`);
